function buildDistricts(table, completeName) {
  return Object.entries(table).flatMap(([city, row]) => {
    const [country, ...entries] = row.split('|');
    const cityShort = city.slice(0, -1);
    return entries.map((entry) => {
      const [label, lat, lon] = entry.split(',');
      const name = completeName(label);
      const stem = name.slice(0, -1);
      return {
        place: { name, state: city, country, lat: Number(lat), lon: Number(lon) },
        keys: [stem, name, `${cityShort}${stem}`, `${city}${stem}`],
      };
    });
  });
}

const DISTRICT_PLACES = [
  ...buildDistricts(DISTRICTS, (label) => `${label}區`),
  ...buildDistricts(TOWNSHIPS, (label) => label),
];

const ADMIN_SUFFIX = /[市縣區鄉鎮]$/;
const UNIT_SUFFIX = /[區鄉鎮市]$/;
const CJK = /[\u3400-\u9fff]/;

function normalize(text) {
  const compact = text.trim().replace(/臺/g, '台').replace(/\s+/g, '');
  return compact.length > 1 ? compact.replace(ADMIN_SUFFIX, '') : compact;
}

export function hasChinese(text) {
  return CJK.test(text);
}

export function searchChinesePlaces(query, limit = 5) {
  const needle = normalize(query);
  if (!needle) {
    return [];
  }
  const suffix = query.trim().match(UNIT_SUFFIX)?.[0] ?? null;
  const matches = (key) => (suffix ? key === needle : key.startsWith(needle));
  const districts = DISTRICT_PLACES.filter(
    ({ place, keys }) => (!suffix || place.name.endsWith(suffix)) && keys.some(matches)
  ).map(({ place }) => place);
  const cities = PLACES.filter(
    (place) => place.name.startsWith(needle) || (districts.length === 0 && needle.startsWith(place.name))
  );
  return [...cities, ...districts].slice(0, limit);
}
