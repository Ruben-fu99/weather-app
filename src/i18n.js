const DEFAULT_LANGUAGE = 'zh';
const HTML_LANGUAGES = { zh: 'zh-Hant', en: 'en' };
const API_LANGUAGES = { zh: 'zh_tw', en: 'en' };

let language = DEFAULT_LANGUAGE;

export function getLanguage() {
  return language;
}

export function setLanguage(next) {
  language = DICTIONARIES[next] ? next : DEFAULT_LANGUAGE;
}

export function apiLanguage() {
  return API_LANGUAGES[language];
}

export function detectLanguage(browserLanguage) {
  return String(browserLanguage ?? '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function t(key, params = {}) {
  const template = DICTIONARIES[language][key] ?? DICTIONARIES[DEFAULT_LANGUAGE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function translatePage(root = document) {
  document.documentElement.lang = HTML_LANGUAGES[language];
  document.title = t('app.title');

  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  root.querySelectorAll('[data-i18n-attrs]').forEach((element) => {
    element.dataset.i18nAttrs.split(',').forEach((pair) => {
      const [attribute, key] = pair.split(':');
      element.setAttribute(attribute, t(key));
    });
  });
}
